import assert from 'node:assert/strict';
await import('../public/schedule.js');
await import('../public/program-chainage.js');
const S=globalThis.T2W_SCHEDULE;
const P=globalThis.T2W_PROGRAM_CHAINAGE;
assert.ok(S,'schedule API exposed');
assert.ok(P,'programme chainage API exposed');
const all=P.sortActivities([...(S.SCHEDULE.PHW||[]),...(S.SCHEDULE.PWG||[])]);
assert.equal(all[0].sec,'PWG');
assert.equal(all[0].activity,'1240');
assert.equal(all[0].start,'22-Feb-27');
assert.equal(all[1].sec,'PHW');
assert.equal(all[1].activity,'1300');
assert.equal(all[1].start,'23-Feb-27');
assert.equal(all[2].sec,'PHW');
assert.equal(all[2].activity,'1130');
assert.equal(all[2].start,'24-Feb-27');
assert.equal(P.chooseActivity('PWG',26500,all).activity,'1240');
assert.equal(P.chooseActivity('PHW',19130,all).activity,'1300');
assert.equal(P.classifyText('Air valve AV-011'),'Valves');
assert.equal(P.classifyText('Major road crossing'),'Major road crossing');
assert.equal(P.classifyText('Trench Stop and Bulkhead'),'Trench stops');
console.log('programme chainage tests passed:',all.length,'activities');
